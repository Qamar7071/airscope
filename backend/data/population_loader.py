"""Population-density and elevation surfaces from bundled CSV files.

``datasets/population_density.csv`` columns:
    city, latitude, longitude, population_density_per_km2
``datasets/elevation.csv`` columns:
    city, latitude, longitude, elevation_m

Both files are regular lat/lon lattices per city. The bundled versions are
documented approximations generated by ``python -m data.demo_generator``
(see ``datasets/README.md``). They can be replaced by real products (e.g.
WorldPop or GHSL population, Copernicus DEM elevation) resampled to the same
schema without any code change.
"""
from __future__ import annotations

import logging
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

from config import get_settings
from geospatial.surfaces import GriddedSurface

logger = logging.getLogger(__name__)

POPULATION_FILE = "population_density.csv"
ELEVATION_FILE = "elevation.csv"


class SurfaceUnavailable(RuntimeError):
    """Raised when a city has no rows in a surface CSV."""


@lru_cache(maxsize=8)
def _read_table(path: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    df["city"] = df["city"].astype(str).str.lower()
    return df


class _SurfaceLoader:
    file_name: str = ""
    value_col: str = ""
    lower_bound: float | None = None

    def __init__(self, datasets_dir: Path | None = None):
        self.path = Path(datasets_dir or get_settings().datasets_dir) / self.file_name
        self._surfaces: dict[str, GriddedSurface] = {}

    def available(self) -> bool:
        return self.path.exists()

    def surface(self, city_id: str) -> GriddedSurface:
        city_id = city_id.lower()
        if city_id not in self._surfaces:
            if not self.path.exists():
                raise SurfaceUnavailable(f"{self.path} not found - run `python -m data.demo_generator`")
            table = _read_table(str(self.path))
            rows = table[table["city"] == city_id]
            if rows.empty:
                raise SurfaceUnavailable(f"No {self.value_col} rows for city '{city_id}' in {self.path.name}")
            self._surfaces[city_id] = GriddedSurface.from_frame(rows, self.value_col, name=self.value_col)
        return self._surfaces[city_id]

    def sample(self, city_id: str, lat, lon) -> np.ndarray:
        values = np.asarray(self.surface(city_id).sample(lat, lon), dtype=float)
        if self.lower_bound is not None:
            values = np.maximum(values, self.lower_bound)
        return values


class PopulationLoader(_SurfaceLoader):
    """Population density in persons per km²."""

    file_name = POPULATION_FILE
    value_col = "population_density_per_km2"
    lower_bound = 0.0

    def density_at(self, city_id: str, lat, lon) -> np.ndarray:
        return self.sample(city_id, lat, lon)


class ElevationLoader(_SurfaceLoader):
    """Ground elevation in metres above sea level."""

    file_name = ELEVATION_FILE
    value_col = "elevation_m"

    def elevation_at(self, city_id: str, lat, lon) -> np.ndarray:
        return self.sample(city_id, lat, lon)


@lru_cache(maxsize=1)
def get_population_loader() -> PopulationLoader:
    return PopulationLoader()


@lru_cache(maxsize=1)
def get_elevation_loader() -> ElevationLoader:
    return ElevationLoader()
